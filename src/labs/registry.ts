/// <reference types="vite/client" />
/**
 * The lab registry: id → an interactive exhibit the reader controls directly.
 *
 * A criterion record points at labs by id in its `labs` field; when it has any, the criterion
 * page shows a "Try it yourself" section. Labs add to a record's fail and pass examples, never
 * replace them.
 *
 * Each lab lives in its own folder, `src/labs/<lab>/`, whose `lab.ts` default-exports its entry
 * (or the few entries that share one component file). The registry collects every `lab.ts` it
 * finds, so adding a lab is adding a folder: nothing here is edited. `src/labs/INDEX.md` lists
 * them, generated by `npm run labs:index`.
 *
 * Every lab renders inside the lab shell (`shared/LabShell.tsx`): mock, controls, one verdict,
 * Reset, and one polite live region. `docs/CONVENTIONS.md` ("Labs") says how to add one.
 */

import type { CriterionRecord } from '../criteria/types';
import type { LabEntry, LabModule } from './shared/labEntry';

export type { LabEntry, LabModule, LabProps, LabSteps } from './shared/labEntry';

/** One registered lab and the folder it lives in, e.g. `fade-text`. */
export type FolderLab = { readonly folder: string; readonly lab: LabEntry };

/**
 * Flattens `lab.ts` modules, keyed by path as `import.meta.glob` gives them, into the lab list in
 * folder order. Throws on a duplicate lab id, or on a lab that lists a criterion twice.
 */
export function collectLabs(modules: Readonly<Record<string, LabModule>>): readonly FolderLab[] {
  const out: FolderLab[] = [];
  const seen = new Map<string, string>();
  for (const path of Object.keys(modules).sort()) {
    const folder = /^\.\/([^/]+)\/lab\.ts$/.exec(path)?.[1];
    if (!folder) throw new Error(`labs: ${path} is not a lab folder's lab.ts`);
    const exported = modules[path]!.default;
    const entries: readonly LabEntry[] = Array.isArray(exported) ? exported : [exported as LabEntry];
    if (entries.length === 0) throw new Error(`labs: ${folder}/lab.ts registers no lab`);
    for (const lab of entries) {
      const other = seen.get(lab.id);
      if (other) throw new Error(`labs: lab id "${lab.id}" is registered by ${other} and ${folder}`);
      seen.set(lab.id, folder);
      const twice = lab.criteria.filter((c, i) => lab.criteria.indexOf(c) !== i);
      if (twice.length) throw new Error(`labs: ${lab.id} lists criterion ${twice.join(', ')} twice`);
      out.push({ folder, lab });
    }
  }
  return out;
}

/** Every registered lab with its folder. */
export const LAB_FOLDERS: readonly FolderLab[] = collectLabs(
  import.meta.glob<LabModule>('./*/lab.ts', { eager: true }),
);

export const LABS: readonly LabEntry[] = LAB_FOLDERS.map((l) => l.lab);

export function labById(id: string): LabEntry | undefined {
  return LABS.find((l) => l.id === id);
}

/** The ids on a record that no registered lab answers to. Empty when every reference resolves. */
export function unresolvedLabs(record: Pick<CriterionRecord, 'labs'>): readonly string[] {
  return (record.labs ?? []).filter((id) => labById(id) === undefined);
}

/** The criteria with no lab. Empty when coverage is complete, as it must be. */
export function uncoveredCriteria(
  records: readonly Pick<CriterionRecord, 'num' | 'labs'>[],
): readonly string[] {
  return records.filter((r) => (r.labs ?? []).length === 0).map((r) => r.num);
}

/** The criteria that have a flagship lab built. */
export function flagshipCriteria(): readonly string[] {
  return LABS.flatMap((l) => (l.flagshipFor ? [l.flagshipFor] : []));
}
